#!/usr/bin/env python3
"""Build public/today-classic.css: the original 3.5 Today section styles (main
branch), scoped to web Today only (html:not([data-desktop]) #todayView).
Re-run after editing the source list; the output file is committed."""
import re, sys
SRC = sys.argv[1]  # main-branch styles.css
OUT = sys.argv[2]
KEEP = re.compile(r'\.(habit-carousel|habit-page|habit-card|habit-icon|habit-check|period-note|day-roll|day-schedule|routine-|day-plan-expand|calendar-toolbar|calendar-atmosphere|calendar-card|calendar-day|calendar-grid|weekdays|calendar-legend|legend-|month-orbit|calendar-view-switch|calendar-month-nav|day-number|day-mood|day-percent|heat-\d)')
SKIP = re.compile(r'\.(daily-|hero-card|progress-orbit|mood-card|mood-options|mood-note|voice-reflection|autosave|timeline-|drawer|review-|settings-)|#(calendarGrid|drawer)')
SCOPE = 'html:not([data-desktop]) #todayView'

def scope_one(sel):
    sel = sel.strip()
    m = re.match(r'^html((?:\[[^\]]+\]|\.[\w-]+|:[\w-]+(?:\([^)]*\))?)*)\s+(.*)$', sel, re.S)
    if m:
        return f'html{m.group(1)}:not([data-desktop]) #todayView {m.group(2)}'
    if sel.startswith(('body', ':root')):
        return None
    return f'{SCOPE} {sel}'

def scope(selectors):
    parts = [scope_one(s) for s in re.split(r',(?![^(]*\))', selectors)]
    parts = [p for p in parts if p]
    return ',\n'.join(parts)

css = re.sub(r'/\*.*?\*/', '', open(SRC).read(), flags=re.S)
out, stack, pos = [], [], 0
for m in re.finditer(r'[^{}]+\{|\}', css):
    t = m.group(0)
    if t != '}':
        stack.append((t[:-1].strip(), m.end()))
        continue
    if not stack:
        continue
    sel, body_start = stack.pop()
    if sel.startswith('@'):
        continue
    if not KEEP.search(sel) or SKIP.search(sel):
        continue
    body = css[body_start:m.start()].strip()
    rule = f'{scope(sel)} {{ {body} }}'
    media = [s for s, _ in stack if s.startswith('@media')]
    out.append((media[-1] if media else '', rule))

lines = ['/* GENERATED by scripts/build-today-classic-css.py from the 3.5 (main) styles.css.',
         '   Original Today section styles, scoped to web Today. Do not edit by hand. */']
current = None
for media, rule in out:
    if media != current:
        if current:
            lines.append('}')
        if media:
            lines.append(f'{media} {{')
        current = media
    lines.append(rule)
if current:
    lines.append('}')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(len(out), 'rules')
