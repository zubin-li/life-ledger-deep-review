import { DEMO_EVENTS, demoEventText } from "./demo-life.js";

// Sample calendar for the demo workspace (shown instead of Google Calendar while the demo is active).
export function demoScheduleFor(lang, date, today = new Date()) {
  const s = personaPack(lang).schedule, d = new Date(`${date}T12:00:00`), t = new Date(today); t.setHours(12, 0, 0, 0);
  const offset = Math.round((d - t) / 86400000), weekday = d.getDay();
  const ev = ([start, end, title, allDay], i, routine) => ({ id: `demo-${routine ? "r" : "e"}-${date}-${i}`, date, start, end, title, allDay: Boolean(allDay), routine });
  const dateSeed = Number(date.replaceAll("-", ""));
  const regular = s.routinesByWeekday?.[weekday] || s.routines || [];
  const pool = weekday === 0 || weekday === 6 ? s.weekendPool : s.weekdayPool;
  const varied = [];
  if (pool?.length) {
    const first = (dateSeed * 7 + weekday * 11) % pool.length;
    varied.push(pool[first]);
    if ((dateSeed + weekday) % 3 === 0) varied.push(pool[(first + 5 + (dateSeed % 4)) % pool.length]);
  }
  const routines = regular.map((r, i) => ev(r, i, true));
  const variedEvents = varied.map((r, i) => ev(r, 100 + i, false));
  const life = DEMO_EVENTS.filter(e => -e.d === offset).map((e, i) => ({ id: `demo-life-${date}-${i}`, date, start: e.time, end: e.time ? `${String(Math.min(23, Number(e.time.slice(0, 2)) + 2)).padStart(2, "0")}${e.time.slice(2)}` : "", title: demoEventText(e, lang)[0], allDay: !e.time, routine: false }));
  // all-day first, then by start time — like any calendar
  return [...life, ...(s.oneOff[offset] || []).map((r, i) => ev(r, i, false)), ...routines, ...variedEvents]
    .sort((a, b) => (b.allDay - a.allDay) || String(a.start || "").localeCompare(String(b.start || "")));
}

